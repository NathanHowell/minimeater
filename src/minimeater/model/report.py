"""Generate docs/modeling/bge-large.md and plots.  Run: uv run minimeater-model"""

import argparse
import dataclasses
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy.optimize import brentq  # noqa: E402

from . import flow, thermal  # noqa: E402
from .fans import FANS, Fan, max_flow, required_speed  # noqa: E402
from .params import (  # noqa: E402
    DEFAULT_EGG,
    DEFAULT_INTAKE,
    SCENARIOS,
    TOP_VENT,
    Ambient,
    Egg,
    Intake,
    uncertainty_band,
)
from .control import AirflowMap, PercentPid  # noqa: E402
from .sim import Event, air_flow, simulate  # noqa: E402
from .units import CFM, LB, MMH2O, INCH, air_density, f_to_k, k_to_f  # noqa: E402

TEMPS_F = [150, 180, 225, 275, 325]  # project scope: chili drying to hot-and-fast brisket


def required_cfm(egg: Egg, sc, t_f: float) -> float:
    ss = thermal.steady_state(egg, sc.ambient, f_to_k(t_f), sc.food_load_w)
    return ss.m_air_kg_s / air_density(sc.ambient.t_k) / CFM


def p_required(egg: Egg, intake: Intake, amb: Ambient, q_cfm: float, t_f: float, top: float) -> float:
    t_pit = f_to_k(t_f)
    return flow.system_drop(egg, intake, q_cfm * CFM, amb.t_k, t_pit, top) - flow.stack_draft(egg, amb.t_k, t_pit)


def fan_max_cfm(egg, intake, fan: Fan, amb, t_f, top) -> float:
    return max_flow(fan, 1.0, lambda q: p_required(egg, intake, amb, q / CFM, t_f, top)) / CFM


def natural_draft_cfm(egg, intake, amb, t_f, top, fan: Fan = FANS[1]) -> float:
    """Fan stopped, damper fully open: convective draft pulled through the stopped fan."""
    return air_flow(egg, intake, fan, amb, 0.0, 1.0, f_to_k(t_f), top) / CFM


def max_sustainable_f(egg, intake, fan, sc, top) -> float:
    """Highest steady pit temp where the fan at 100% still supplies the required air."""

    def margin(t_f):
        return fan_max_cfm(egg, intake, fan, sc.ambient, t_f, top) - required_cfm(egg, sc, t_f)

    lo, hi = 150.0, 900.0
    if margin(hi) > 0:
        return hi
    if margin(lo) < 0:
        return float("nan")
    return brentq(margin, lo, hi, xtol=1.0)


def fmt_dba(dba: float) -> str:
    return "<10 (inaudible)" if dba < 10.0 else f"{dba:.1f}"


def md_table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=Path("docs/modeling"))
    args = ap.parse_args()
    img_dir = args.out / "bge-large"
    img_dir.mkdir(parents=True, exist_ok=True)

    egg, intake = DEFAULT_EGG, DEFAULT_INTAKE
    mild, winter = SCENARIOS[0], SCENARIOS[3]
    md: list[str] = []
    w = md.append

    w("# BGE Large airflow & thermal model\n")
    w("_Generated by `uv run minimeater-model` from `src/minimeater/model/`. Do not edit by hand._\n")
    w(
        "First-principles model of a Big Green Egg Large driven through a BBQ Guru-style stainless intake tube "
        f"({intake.tube_od_m / INCH:.3f}\" OD / {intake.tube_id_m * 1000:.1f} mm ID). Most inputs are estimates "
        "(see `params.py`, tagged `[spec]`/`[forum]`/`[est]`). Use the results to rank options and set direction, "
        "not as absolute values; the measurement beads replace the estimates.\n"
    )

    # 1. required air
    w("## 1. Combustion air needed to hold a pit temperature (steady state)\n")
    rows = []
    for sc in SCENARIOS:
        rows.append([sc.name] + [f"{required_cfm(egg, sc, t):.2f}" for t in TEMPS_F])
    w(md_table(["scenario \\ pit temp"] + [f"{t}F" for t in TEMPS_F], rows))
    w("\nCFM at ambient density. Nominal parameters. Uncertainty band (mild calm):\n")
    rows = []
    for name, e in uncertainty_band(egg).items():
        rows.append([name] + [f"{required_cfm(e, mild, t):.2f}" for t in TEMPS_F])
    w(md_table(["params"] + [f"{t}F" for t in TEMPS_F], rows))
    rows = []
    for t in TEMPS_F:
        ss = thermal.steady_state(egg, mild.ambient, f_to_k(t))
        rows.append([
            f"{t}F", f"{ss.fire_w:.0f}", f"{ss.shell_loss_w:.0f}", f"{ss.flue_loss_w:.0f}",
            f"{thermal.fuel_rate_kg_h(egg, ss) / LB:.2f}", f"{k_to_f(ss.t_wall_out_k):.0f}",
        ])
    w("\nEnergy balance, mild calm:\n")
    w(md_table(["pit", "fire W", "shell loss W", "flue loss W", "lump lb/h", "outer shell F"], rows))
    w(
        "\nSanity check: forum reports of 20+ h at 225F on a full Large load (~8-10 lb) imply <=0.4 lb/h, "
        "consistent with the model. Reports of 4-5 h at 400-500F imply ~2 lb/h, ~3x the model; hot cooks "
        "run vents wide open with large excess air and are rarely at thermal steady state, so treat the "
        "high-temperature numbers as a floor.\n"
    )

    fig, ax = plt.subplots(figsize=(7, 4.5))
    ts = np.linspace(200, 650, 30)
    for sc in SCENARIOS:
        ax.plot(ts, [required_cfm(egg, sc, t) for t in ts], label=sc.name)
    band = uncertainty_band(egg)
    ax.fill_between(
        ts,
        [required_cfm(band["low loss"], mild, t) for t in ts],
        [required_cfm(band["high loss"], mild, t) for t in ts],
        alpha=0.15, color="C0", label="mild calm, param band",
    )
    ax.set(xlabel="pit temp (F)", ylabel="air required (CFM)", title="BGE Large: steady-state combustion air")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(img_dir / "required_air.png", dpi=130)
    plt.close(fig)
    w("![required air](bge-large/required_air.png)\n")

    # 2. pressure drop
    w("## 2. Where the pressure goes\n")
    q_ref, t_ref = 3.0, 275
    rows = []
    for name, top in TOP_VENT.items():
        b = flow.breakdown(egg, intake, q_ref * CFM, mild.ambient.t_k, f_to_k(t_ref), top)
        rows.append([name] + [f"{v:.1f}" for v in b.values()] + [f"{sum(b.values()):.1f}", f"{sum(b.values()) / MMH2O:.2f}"])
    keys = list(flow.breakdown(egg, intake, CFM, 293.0, 400.0, 1e-3).keys())
    w(f"Pa at {q_ref} CFM, pit {t_ref}F, 20C ambient, k_box={intake.k_box}:\n")
    w(md_table(["top vent"] + keys + ["total Pa", "total mmH2O"], rows))
    w(
        "\nThe daisy wheel dominates when nearly closed; once it is past ~1/4 open the **intake tube and our "
        "own box internals dominate**. Inside the egg, the grate and charcoal bed are negligible.\n"
    )

    fig, ax = plt.subplots(figsize=(7, 4.5))
    qs = np.linspace(0.0, 12.0, 80)
    for i, (name, top) in enumerate(TOP_VENT.items()):
        ax.plot(qs, [p_required(egg, intake, mild.ambient, q, 275, top) for q in qs], color=f"C{i}", label=f"system: {name}")
    for fan, ls in zip(FANS, ["--", "-.", ":", (0, (5, 1)), (0, (3, 1, 1, 1))]):
        ax.plot(qs, [fan.pressure(q * CFM, 1.0) for q in qs], color="k", ls=ls, lw=1, label=f"fan 100%: {fan.name}")
    ax.set(xlabel="flow (CFM)", ylabel="pressure (Pa)", ylim=(-5, 120), title="System curves (pit 275F) vs fan curves")
    sec = ax.secondary_yaxis("right", functions=(lambda p: p / MMH2O, lambda m: m * MMH2O))
    sec.set_ylabel("mmH2O")
    ax.axhline(0, color="grey", lw=0.5)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=6.5, ncol=2)
    fig.tight_layout()
    fig.savefig(img_dir / "system_curves.png", dpi=130)
    plt.close(fig)
    w("![system curves](bge-large/system_curves.png)\n")

    # 3. natural draft
    w("## 3. Natural draft (fan stopped, damper open)\n")
    rows = []
    for name, top in TOP_VENT.items():
        rows.append([name] + [f"{natural_draft_cfm(egg, intake, mild.ambient, t, top):.2f}" for t in (150, 225, 275, 325)])
    radial = FANS[4]
    rows.append([f"slider 1/4, stopped {radial.name}"] + [
        f"{natural_draft_cfm(egg, intake, mild.ambient, t, TOP_VENT['slider 1/4'], radial):.2f}" for t in (150, 225, 275, 325)
    ])
    rows.append(["**required (mild calm)**"] + [f"**{required_cfm(egg, mild, t):.2f}**" for t in (150, 225, 275, 325)])
    w(f"Convective draft pulled through the stopped {FANS[1].name} (CFM):\n")
    w(md_table(["top vent", "150F", "225F", "275F", "325F"], rows))
    w(
        "\nA stopped axial fan barely obstructs the egg's convective draft, so with the daisy wheel at 1/4 or "
        "more, natural draft through an open damper alone **exceeds** what most of the 150-325F range needs. "
        "A stopped radial blower chokes it below the 225F requirement, so a blower would have to run even "
        "at low-and-slow. So: (a) the damper must seal well when closed (leakage directly sets the minimum "
        "achievable temperature), (b) at low-and-slow the damper angle, not fan speed, is the primary "
        "actuator, and (c) the user should run a small top-vent opening for low-and-slow.\n"
    )

    # 4. fan capability
    w("## 4. Fan capability through this intake\n")
    rows = []
    worst = uncertainty_band(egg)["high loss"]
    for fan in FANS:
        rows.append([
            fan.name, fan.size,
            f"{fan_max_cfm(egg, intake, fan, mild.ambient, 275, TOP_VENT['slider 1/4']):.1f}",
            f"{fan_max_cfm(egg, intake, fan, mild.ambient, 275, TOP_VENT['slider 1/2']):.1f}",
            f"{max_sustainable_f(egg, intake, fan, mild, TOP_VENT['slider 1/2']):.0f}",
            f"{max_sustainable_f(egg, intake, fan, winter, TOP_VENT['slider 1/2']):.0f}",
            f"{max_sustainable_f(worst, intake, fan, winter, TOP_VENT['slider 1/2']):.0f}",
        ])
    w(md_table(
        ["fan", "size", "max CFM (1/4 top, 275F)", "max CFM (1/2 top, 275F)",
         "max steady F (mild, 1/2 top)", "max steady F (winter, 1/2 top)",
         "max steady F (winter, high-loss params)"],
        rows,
    ))
    w(
        "\nEvery candidate's free-air rating is far above what it delivers here: the 31.6 mm tube plus our "
        "box chokes the flow, so static pressure matters more than free-air CFM. The high-loss column is the "
        "conservative case for sizing (the model under-predicts hot-cook fuel burn).\n"
    )

    w("### Operating points: speed, noise, power\n")
    cases = [
        ("hold 225F, mild", mild, 225, TOP_VENT["petals open"], 1.0),
        ("hold 325F, winter", winter, 325, TOP_VENT["slider 1/2"], 1.0),
        ("recover 225F after lid-open (3x hold flow)", mild, 225, TOP_VENT["petals open"], 3.0),
        ("heat-up toward 325F, winter (2x hold flow)", winter, 325, TOP_VENT["slider 1/2"], 2.0),
    ]
    for label, sc, t_f, top, mult in cases:
        q = required_cfm(egg, sc, t_f) * mult
        p = p_required(egg, intake, sc.ambient, q, t_f, top)
        w(f"\n**{label}** - {q:.2f} CFM against {p:.1f} Pa ({p / MMH2O:.2f} mmH2O):\n")
        rows = []
        for fan in FANS:
            op = required_speed(fan, q * CFM, p)
            if not op.feasible:
                rows.append([fan.name, "cannot reach", "-", "-", "-"])
            elif op.s == 0.0:
                rows.append([fan.name, "natural draft enough (damper only)", "-", "-", "-"])
            elif op.below_min:
                duty = op.s / fan.s_min
                rows.append([
                    fan.name, f"{op.s * 100:.0f}% < min {fan.s_min * 100:.0f}%",
                    f"cycle {duty * 100:.0f}% at {fan.rpm_min:.0f} rpm",
                    f"{fmt_dba(fan.noise_dba(fan.s_min))} (while on)", f"{fan.watts(fan.s_min) * duty:.3f}",
                ])
            else:
                rows.append([fan.name, f"{op.s * 100:.0f}%", f"{op.rpm:.0f} rpm", fmt_dba(op.dba), f"{op.watts:.3f}"])
        w(md_table(["fan", "speed", "rpm / mode", "est dB(A)", "est W"], rows))
    w(
        "\nNoise is the datasheet free-air max scaled by 50*log10(speed); real noise against back-pressure and "
        "inside a box will differ - the bake-off measures it.\n"
    )

    # 5. sensitivity
    w("## 5. Sensitivity: our box and the tube matter most\n")
    a6 = FANS[1]
    rows = []
    for k_box in (0.5, 1.0, 2.0, 4.0, 8.0):
        it = dataclasses.replace(intake, k_box=k_box)
        rows.append([f"{k_box}", f"{fan_max_cfm(egg, it, a6, mild.ambient, 275, TOP_VENT['slider 1/2']):.1f}"])
    w(f"{a6.name} max flow (pit 275F, top 1/2) vs box loss coefficient k_box:\n")
    w(md_table(["k_box", "max CFM"], rows))
    rows = []
    for od_in, id_mm in ((1.0, 22.0), (1.315, 26.6), (1.375, 31.6), (1.5, 35.0), (2.0, 47.0)):
        it = dataclasses.replace(intake, tube_id_m=id_mm / 1000)
        rows.append([f"{od_in}\" OD / {id_mm} mm ID", f"{fan_max_cfm(egg, it, a6, mild.ambient, 275, TOP_VENT['slider 1/2']):.1f}"])
    w(f"\n{a6.name} max flow vs intake tube size:\n")
    w(md_table(["tube", "max CFM"], rows))
    w("\n(1.315\" row assumes a 1\" sch40 NPT nipple, 26.6 mm ID.)\n")

    # 6. dynamics
    w("## 6. Closed-loop dynamics (PI, P=2 %/F, I=0.005 %/F/s)\n")
    w(
        "Light at t=0 with a starter in a cold egg, setpoint 225F, lid opened for 2 min at 3 h, setpoint "
        "350F at 4 h. Top vent 1/4, mild calm. Damper-first output mapping: the flap opens proportionally over "
        "0-50% output and the fan ramps over 50-100% (time-averaged below its minimum speed). An earlier "
        "on/off-damper version limit-cycled +/-15F at 225F because natural draft through a fully open "
        "flap already exceeds the low-and-slow requirement (section 3).\n"
    )
    events = [Event(3 * 3600, lid_open_s=120), Event(4 * 3600, setpoint_f=350.0)]
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(8, 6), sharex=True)
    rows = []
    for i, fan in enumerate(FANS):
        r = simulate(egg, intake, fan, mild.ambient, TOP_VENT["slider 1/4"], events, 6 * 3600, PercentPid())
        h = r.t_s / 3600
        ax1.plot(h, r.pit_f, color=f"C{i}", lw=1, label=fan.name)
        ax2.plot(h, r.output * 100, color=f"C{i}", lw=0.8)
        reach = r.t_s[np.argmax(r.pit_f >= 220)] / 60
        first = r.t_s < 3 * 3600
        after_lid = (r.t_s > 3 * 3600 + 120) & (r.t_s < 4 * 3600)
        rec_idx = np.argmax(np.abs(r.pit_f[after_lid] - 225) < 5)
        rec = rec_idx * (r.t_s[1] - r.t_s[0]) / 60
        hold = (r.t_s > 2 * 3600) & (r.t_s < 3 * 3600)
        step = r.t_s >= 4 * 3600
        reach350 = (r.t_s[step][np.argmax(r.pit_f[step] >= 345)] - 4 * 3600) / 60 if (r.pit_f[step] >= 345).any() else float("nan")
        rows.append([
            fan.name, f"{reach:.0f}", f"{r.pit_f[first].max() - 225:.0f}", f"{r.output[hold].mean() * 100:.1f}",
            f"{rec:.0f}", f"{reach350:.0f}",
        ])
    ax1.axhline(225, color="grey", lw=0.5)
    ax1.axhline(350, color="grey", lw=0.5)
    ax1.set(ylabel="pit (F)", title="Closed-loop sim per fan")
    ax1.legend(fontsize=7)
    ax1.grid(alpha=0.3)
    ax2.set(xlabel="hours", ylabel="output %")
    ax2.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(img_dir / "closed_loop.png", dpi=130)
    plt.close(fig)
    w(md_table(
        ["fan", "min to 220F", "overshoot F", "mean output @225 %", "lid recovery min", "min to 345F after step"],
        rows,
    ))
    w("\n![closed loop](bge-large/closed_loop.png)\n")
    w(
        "\nFan choice barely changes control quality. Gain sweep with the NF-A6x25 (std dev of pit temp in "
        "the hold windows):\n"
    )
    rows = []
    for kp, ki in ((0.04, 0.0002), (0.04, 0.00005), (0.02, 0.0001), (0.02, 0.00005), (0.01, 0.00005)):
        r = simulate(egg, intake, FANS[1], mild.ambient, TOP_VENT["slider 1/4"], events, 6 * 3600, PercentPid(kp, ki))
        h225 = (r.t_s > 2 * 3600) & (r.t_s < 3 * 3600)
        h350 = r.t_s > 5 * 3600
        rows.append([
            f"{kp * 100:g}", f"{ki * 100:g}", f"{r.pit_f[r.t_s < 3 * 3600].max() - 225:.0f}",
            f"{r.pit_f[h225].std():.1f}", f"{r.pit_f[h350].std():.1f}",
        ])
    w(md_table(["P %/F", "I %/F/s", "startup overshoot F", "sd @225", "sd @350"], rows))
    w(
        "\nHeaterMeter's defaults (P=4, I=0.02) limit-cycle on this plant, and gains stable at 225F can "
        "oscillate at 350F (plant gain changes with temperature): autotune and possibly gain scheduling are "
        "needed. Startup overshoot (40-80F) is set by running 100% output while the fire spreads, "
        f"regardless of gains; the shell time constant is ~{thermal.time_constant_h(egg):.1f} h, so overshoot "
        "is slow to bleed off. The firmware needs a startup mode (output ramp/cap, or D on measurement) "
        "rather than plain PI from cold.\n"
    )

    w("## 7. Actuator inversion (what the firmware commands)\n")
    amap = AirflowMap(egg, intake, FANS[1])
    amb20 = mild.ambient
    fig, (ax, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    rows = []
    for t_f in (150.0, 225.0, 325.0):
        row = amap._row(amb20, t_f)
        ax.plot(amap.us, row, label=f"pit {t_f:.0f}F")
        q_min, q_max = amap.limits(amb20, t_f)
        q_open = float(np.interp(1.0, amap.us, row))
        q_fan_min = float(np.interp(1.0 + FANS[1].s_min, amap.us, row))
        rows.append([f"{t_f:.0f}", f"{q_min:.3f}", f"{q_open:.2f}", f"{q_fan_min:.2f}", f"{q_max:.2f}"])
    ax.axvspan(1.0, 1.0 + FANS[1].s_min, color="0.9", label="fan duty-cycled")
    ax.set(xlabel="actuator u (0-1 flap open, fan stopped; 1-2 fan speed, flap open)", ylabel="airflow CFM",
           title=f"Airflow map, {FANS[1].name}, 20C calm, top 1/4")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7)
    frac = np.linspace(0, 1, 101)
    ax2.plot(frac * 100, np.degrees(np.arccos(1 - frac)))
    ax2.set(xlabel="flap open area %", ylabel="flap angle from closed (deg)", title="Butterfly flap: 1 - cos(angle) [est]")
    ax2.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(img_dir / "actuator_map.png", dpi=130)
    plt.close(fig)
    w(md_table(["pit F", "flap closed (leak) CFM", "flap open, fan off CFM", "fan at min speed CFM", "fan full CFM"], rows))
    w(
        "\n![actuator map](bge-large/actuator_map.png)\n\n"
        "The controllers command airflow; firmware (`minimeater-core::model::airflow::AirflowMap`, parity-tested "
        "against `control.AirflowMap`) inverts this table at the measured pit temperature, damper first. "
        f"Below the fan's minimum continuous speed ({FANS[1].s_min * 100:.0f}%) the fan alternates between off "
        "and minimum (delta-sigma, 10 s minimum dwell; `FanCycler`) so the average matches the command, which is "
        "what the table assumes. The flap angle uses the projected-area law of a butterfly in a round tube until "
        "CFD/bench data (`.2.13`) replaces it. The table is built from the firmware-side model with an assumed "
        "top vent; the MPC's disturbance estimate absorbs the error.\n"
    )

    w("## Parameters\n")
    w(md_table(["Egg", "value"], [[k, v] for k, v in dataclasses.asdict(egg).items()]))
    w("")
    w(md_table(["Intake", "value"], [[k, v] for k, v in dataclasses.asdict(intake).items()]))
    w("")
    w(md_table(["Top vent", "area cm^2"], [[k, f"{v * 1e4:.0f}"] for k, v in TOP_VENT.items()]))
    w("")
    w(md_table(
        ["Fan", "kind", "CFM", "mmH2O", "rpm", "dB(A)", "W", "rpm min", "notes"],
        [[f.name, f.kind, f.qmax_cfm, f.pmax_mmh2o, f.rpm_max, f.dba_max, f.watts_max, f.rpm_min, f.notes] for f in FANS],
    ))
    w("")

    (args.out / "bge-large.md").write_text("\n".join(md))
    print(f"wrote {args.out / 'bge-large.md'}")


