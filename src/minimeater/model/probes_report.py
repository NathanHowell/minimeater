"""Probe front-end error budget -> docs/modeling/probes.md.  Run: uv run minimeater-probes"""

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from . import thermal  # noqa: E402
from .params import DEFAULT_EGG, Ambient  # noqa: E402
from .probes import ADCS, GRID_F, PROBES, FrontEnd, detect_thresholds, e12_range, worst_f  # noqa: E402
from .report import md_table  # noqa: E402
from .units import CFM, air_density, c_to_k, f_to_k  # noqa: E402

CHOSEN = FrontEnd()
BUDGET_TEMPS_F = (32.0, 150.0, 225.0, 325.0, 500.0)


def fmt_r(r: float) -> str:
    return f"{r / 1e6:.2f}M" if r >= 1e6 else f"{r / 1e3:.1f}k" if r >= 1e3 else f"{r:.0f}"


def ambient_sensitivity(t_f: float) -> float:
    """d(steady-state airflow)/d(ambient), CFM per C, at pit t_f."""
    q = [
        thermal.steady_state(DEFAULT_EGG, Ambient(c_to_k(t), 0.0), f_to_k(t_f)).m_air_kg_s / air_density(c_to_k(t)) / CFM
        for t in (15.0, 25.0)
    ]
    return (q[1] - q[0]) / 10.0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=Path("docs/modeling"))
    args = ap.parse_args()
    img_dir = args.out / "probes"
    img_dir.mkdir(parents=True, exist_ok=True)
    md: list[str] = []
    w = md.append
    w("# Probe front-end error budget\n")
    w("_Generated by `uv run minimeater-probes` from `src/minimeater/model/probes*.py`. Do not edit by hand._\n")
    w(
        "Topology per jack: `VREF - R_bias - AINx - probe NTC - AGND`, single-ended. A ratiometric ADC "
        "(ADS1x20) takes its reference from the same VREF, so it reads `x = R_t/(R_t+R_bias)` and supply "
        "drift cancels. Errors are worst-case magnitudes, summed linearly, in F.\n"
    )

    w("## Probe families\n")
    rows = [[p.name, *(fmt_r(p.r(f_to_k(t))) for t in (32, 77, 225, 325, 500, 700)), p.source] for p in PROBES]
    w(md_table(["probe", "32F", "77F", "225F", "325F", "500F", "700F", "coefficients"], rows))
    w("")

    w("## Bias resistor and ADC sweep\n")
    w(
        "Worst design-attributable error over all probe families at 32-500F. Any jack may hold any probe in "
        "either role. Probe-intrinsic terms (lead resistance, insulation leakage) are excluded here and "
        "shown in the budget below.\n"
    )
    biases = e12_range(4.7e3, 470e3)
    fig, ax = plt.subplots(figsize=(7, 4))
    rows = []
    for adc in ADCS:
        ys = [worst_f(FrontEnd(r_bias=rb, adc=adc)) for rb in biases]
        ax.plot(biases, ys, marker=".", label=adc.name)
        best = int(np.argmin(ys))
        rows.append([adc.name, fmt_r(biases[best]), f"{ys[best]:.2f}", f"{worst_f(FrontEnd(adc=adc)):.2f}", adc.notes])
    ax.axvline(CHOSEN.r_bias, color="k", lw=0.6, ls="--")
    ax.set(xscale="log", yscale="log", xlabel="R_bias (ohm)", ylabel="worst error F", title="Front-end error vs bias")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(img_dir / "bias-sweep.png", dpi=120)
    plt.close(fig)
    w(md_table(["ADC", "best R_bias", "worst F at best", f"worst F at {fmt_r(CHOSEN.r_bias)}", "basis"], rows))
    w("\n![bias sweep](probes/bias-sweep.png)\n")

    w(f"## Per-temperature error, chosen design ({fmt_r(CHOSEN.r_bias)}, {CHOSEN.adc.name})\n")
    rows = [[p.name, *(f"{CHOSEN.total_k(p, f_to_k(t), False) * 1.8:.2f}" for t in GRID_F)] for p in PROBES]
    w(md_table(["probe", *(f"{t:.0f}F" for t in GRID_F)], rows))
    w("")

    w("## Error budget by mechanism (F)\n")
    terms = list(CHOSEN.errors_k(PROBES[0], f_to_k(225.0)).keys())
    rows = []
    for p in PROBES:
        for t in BUDGET_TEMPS_F:
            e = CHOSEN.errors_k(p, f_to_k(t))
            rows.append([p.name, f"{t:.0f}", *(f"{e[k] * 1.8:.3f}" for k in terms)])
    w(md_table(["probe", "T F", *terms], rows))
    w(
        "\nLead resistance and insulation leakage belong to the probe, not the front-end: 1 ohm of lead "
        f"and a {CHOSEN.r_shunt / 1e6:.0f} M ohm damp-insulation shunt. They are why high-resistance probes "
        "(1M-class Maverick) read poorly near freezing whatever the front-end.\n"
    )

    d = detect_thresholds(CHOSEN)
    w("## Probe present / fault detection\n")
    w(
        md_table(
            ["condition", "ratio x"],
            [
                ["short (below)", f"{d.short_below:.2e}"],
                ["hottest valid reading (700F, lowest-R family)", f"{d.hottest_valid:.2e}"],
                ["coldest valid reading (-20F, highest-R family)", f"{d.coldest_valid:.5f}"],
                ["open (above)", f"{d.open_above:.5f}"],
            ],
        )
    )
    w("")

    w("## Ambient sensor accuracy requirement\n")
    rows = []
    for t in (150.0, 225.0, 325.0):
        s = ambient_sensitivity(t)
        rows.append([f"{t:.0f}", f"{-s:.4f}", f"{-s * 116.0:.2f}"])
    w(md_table(["pit F", "feedforward CFM per C ambient", "pit offset F per C error (at 116 F/CFM)"], rows))
    w(
        "\nThe offset is transient, because the integral/disturbance estimate removes it. It shows a 2C "
        "sensor is ample, and that placement (keeping clear of board and egg heat) matters more than the "
        "sensor's spec.\n"
    )
    (args.out / "probes.md").write_text("\n".join(md))
    print(f"wrote {args.out / 'probes.md'}")
