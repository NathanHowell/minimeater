//! Offset-free linear MPC on the scheduled FOPDT model.
//!
//! Model (per control period dt, a = exp(-dt/tau)):
//!   y+ = a y + (1-a) (y_op + K (q_{k-delay} - q_op) + d),   d a random walk (Kalman-estimated)
//! linearised around the setpoint `y_op` and its feedforward airflow `q_op`. The disturbance `d`
//! absorbs fuel, weather, food load and model error, which makes the loop offset-free.
//!
//! Decision variables: `BLOCKS` airflow levels held over equal slices of the horizon. Cost:
//!   sum_j w_j e_j^2 / n + move_weight * sum_b (q_b - q_{b-1})^2,   w_j = overshoot_weight if e_j > 0
//! with box constraints [q_min, q_max]. The cost is convex and C1 (piecewise quadratic), so it is
//! solved exactly by a projected Newton method: the generalised Hessian at the current sign pattern
//! gives a 6x6 box QP (projected Gauss-Seidel), followed by an Armijo backtrack on the true cost.
//! Nothing horizon-sized is stored: predictions, the step-response matrix and the reference preview
//! are regenerated by recursion on every pass, so the controller is a few hundred bytes.

use libm::{exp, round};

use super::{Feedforward, LidRecovery, Obs, RefShaper, Schedule, Snapshot};

pub const BLOCKS: usize = 6;
/// Longest dead time representable, in control periods (theta <= 900 s at dt >= 4 s).
const PAST_CAP: usize = 256;

#[derive(Clone, Debug)]
pub struct Mpc {
    pub schedule: Schedule,
    pub shaper: RefShaper,
    pub lid: LidRecovery,
    pub horizon_s: f64,
    pub overshoot_weight: f64,
    /// F^2 per CFM^2 of move between blocks.
    pub move_weight: f64,
    pub q_proc_y: f64,
    pub q_proc_d: f64,
    pub r_meas: f64,
    /// Kalman state [pit F, disturbance F] and covariance; `None` until the first step.
    x: Option<[f64; 2]>,
    p: [[f64; 2]; 2],
    past: Past,
    q_prev: f64,
    /// Schedule revision, setpoint and gain the estimate was last computed with (bumpless updates).
    model_prev: (u32, f64, f64),
    /// Newton iterations used by the last solve (telemetry).
    pub last_iters: u32,
    /// Set by [`Self::resume`] until the first step.
    trim: Option<f64>,
}

impl Default for Mpc {
    fn default() -> Self {
        Self::new(Schedule::default())
    }
}

impl Mpc {
    pub fn new(schedule: Schedule) -> Self {
        Self {
            schedule,
            shaper: RefShaper::default(),
            lid: LidRecovery::default(),
            horizon_s: 1800.0,
            overshoot_weight: 8.0,
            move_weight: 30.0,
            q_proc_y: 0.5,
            q_proc_d: 0.3,
            r_meas: 0.3 * 0.3,
            x: None,
            p: [[1.0, 0.0], [0.0, 25.0]],
            past: Past::default(),
            q_prev: 0.0,
            model_prev: (0, f64::NAN, f64::NAN),
            last_iters: 0,
            trim: None,
        }
    }

    /// Kalman disturbance estimate, F: how much hotter (or colder) the egg runs than the model says.
    /// Fire-out / fuel-low detection (`.4.19`) watches this.
    pub fn disturbance_f(&self) -> f64 {
        self.x.map_or(0.0, |x| x[1])
    }

    pub fn step(&mut self, obs: &Obs, ff: &impl Feedforward, dt: f64) -> f64 {
        self.start(obs, ff);
        let lin = self.linearise(obs, ff, dt);
        let x = *self.x.get_or_insert([obs.pit_f, 0.0]);

        let prev = Snapshot {
            q: self.q_prev,
            state: x[1],
        };
        if let Some(o) = self.lid.update(obs, dt, prev) {
            // The lid transient is not in the model: track the measurement, keep the learned
            // disturbance (as it was before the drop), and replay the pre-lid airflow until back
            // near setpoint.
            let d = o.restore.map_or(x[1], |s| s.state);
            self.x = Some([obs.pit_f, d]);
            self.commit(o.q, lin.delay);
            return o.q.clamp(0.0, obs.q_max);
        }

        let xp = self.estimate(obs, &lin);
        let Lin {
            a,
            k: kk,
            delay,
            y_op,
            q_op,
        } = lin;

        // Roll the model through the dead time with already-committed inputs.
        let d = xp[1];
        let mut y = xp[0];
        for i in (0..delay).rev() {
            y = a * y + (1.0 - a) * (y_op + kk * (self.past.back(i) - q_op) + d);
        }

        self.shaper.step(obs.sp_f, obs.pit_f, dt);
        let n = ((self.horizon_s / dt) as usize).max(BLOCKS);
        let problem = Problem {
            n,
            a,
            gain: (1.0 - a) * kk,
            y0: y,
            c: y_op - kk * q_op + d,
            preview_skip: delay,
            shaper: &self.shaper,
            sp: obs.sp_f,
            dt,
            overshoot_weight: self.overshoot_weight,
            move_weight: self.move_weight,
            q_prev: self.q_prev,
        };
        let (qv, iters) = problem.solve(obs.q_min, obs.q_max);
        self.last_iters = iters;
        let q = qv[0];
        self.commit(q, delay);
        q
    }

    /// Starting fresh on an egg that was already running (power cut, controller switch, probe fault).
    /// `trim_cfm`: how much more airflow than the feedforward this egg needs to hold its setpoint,
    /// as last seen (0 if unknown). The first step takes the dead time already elapsed as having had
    /// that airflow at the pit's current temperature, instead of none, and starts the disturbance
    /// estimate where the trim says, so the controller does not have to relearn the egg. Before the
    /// first step only.
    pub fn resume(&mut self, trim_cfm: f64) {
        if self.x.is_none() {
            self.trim = Some(trim_cfm);
        }
    }

    fn start(&mut self, obs: &Obs, ff: &impl Feedforward) {
        if self.x.is_none()
            && let Some(trim) = self.trim.take()
        {
            self.q_prev = (ff.q_cfm(obs.pit_f.min(obs.sp_f)) + trim).max(0.0);
            self.past = Past::default();
            // steady state y_op + K (q - q_op) + d = setpoint at q = q_op + trim
            self.x = Some([obs.pit_f, -self.schedule.at(obs.sp_f).k * trim]);
        }
    }

    /// One control period in which something else (autotune, manual mode) commanded `q_applied`:
    /// keeps the Kalman estimate and the dead-time history consistent, so control resumes bumplessly.
    pub fn track(&mut self, obs: &Obs, ff: &impl Feedforward, q_applied: f64, dt: f64) {
        self.start(obs, ff);
        let lin = self.linearise(obs, ff, dt);
        self.x.get_or_insert([obs.pit_f, 0.0]);
        self.estimate(obs, &lin);
        self.shaper.step(obs.sp_f, obs.pit_f, dt);
        self.commit(q_applied, lin.delay);
    }

    /// The scheduled model at this setpoint, discretised at `dt`; pads the input history to the
    /// dead time.
    fn linearise(&mut self, obs: &Obs, ff: &impl Feedforward, dt: f64) -> Lin {
        let m = self.schedule.at(obs.sp_f);
        let delay = (round(m.theta_s / dt) as usize).min(PAST_CAP - 1);
        while self.past.len() < delay + 1 {
            self.past.push_front(self.q_prev);
        }
        let q_op = ff.q_cfm(obs.sp_f);
        // A learned schedule update (autotune) changes the steady state the model predicts for the
        // current airflow, y_op + K (q - q_op) + d. Re-anchor d so that prediction is unchanged;
        // otherwise the update itself kicks the pit. Setpoint moves are left alone.
        let rev = self.schedule.revision();
        let (rev_prev, sp_prev, k_prev) = self.model_prev;
        if let Some(x) = self.x.as_mut()
            && rev != rev_prev
            && sp_prev == obs.sp_f
        {
            x[1] += (k_prev - m.k) * (self.q_prev - q_op);
        }
        self.model_prev = (rev, obs.sp_f, m.k);
        Lin {
            a: exp(-dt / m.tau_s),
            k: m.k,
            delay,
            y_op: obs.sp_f,
            q_op,
        }
    }

    /// Kalman predict + update of [pit, disturbance]; the state must be initialised.
    fn estimate(&mut self, obs: &Obs, lin: &Lin) -> [f64; 2] {
        let Lin {
            a,
            k: kk,
            delay,
            y_op,
            q_op,
        } = *lin;
        let x = self.x.expect("estimator initialised");
        let q_delayed = self.past.back(delay);
        let f = [[a, 1.0 - a], [0.0, 1.0]];
        let mut xp = [
            f[0][0] * x[0] + f[0][1] * x[1] + (1.0 - a) * (y_op + kk * (q_delayed - q_op)),
            x[1],
        ];
        let p = self.p;
        let fp = [
            [
                f[0][0] * p[0][0] + f[0][1] * p[1][0],
                f[0][0] * p[0][1] + f[0][1] * p[1][1],
            ],
            [p[1][0], p[1][1]],
        ];
        let mut pp = [
            [fp[0][0] * f[0][0] + fp[0][1] * f[0][1] + self.q_proc_y, fp[0][1]],
            [fp[1][0] * f[0][0] + fp[1][1] * f[0][1], fp[1][1] + self.q_proc_d],
        ];
        let s = pp[0][0] + self.r_meas;
        let kg = [pp[0][0] / s, pp[1][0] / s];
        let innov = obs.pit_f - xp[0];
        xp[0] += kg[0] * innov;
        xp[1] += kg[1] * innov;
        let row0 = pp[0];
        for (i, k) in kg.iter().enumerate() {
            for j in 0..2 {
                pp[i][j] -= k * row0[j];
            }
        }
        self.x = Some(xp);
        self.p = pp;
        xp
    }

    fn commit(&mut self, q: f64, delay: usize) {
        self.q_prev = q;
        self.past.push_back(q);
        self.past.keep_last(delay + 1);
    }
}

/// The scheduled FOPDT discretised at the control period, around the setpoint operating point.
#[derive(Clone, Copy)]
struct Lin {
    a: f64,
    k: f64,
    delay: usize,
    y_op: f64,
    q_op: f64,
}

/// One MPC solve. Index j = 0..n is the prediction j+1 periods past the dead time.
struct Problem<'a> {
    n: usize,
    a: f64,
    /// (1 - a) K: response of y_{j+1} to the input applied at j.
    gain: f64,
    y0: f64,
    /// Steady state the free response decays to: y_op - K q_op + d.
    c: f64,
    preview_skip: usize,
    shaper: &'a RefShaper,
    sp: f64,
    dt: f64,
    overshoot_weight: f64,
    move_weight: f64,
    q_prev: f64,
}

impl Problem<'_> {
    fn block(&self, j: usize) -> usize {
        (j * BLOCKS / self.n).min(BLOCKS - 1)
    }

    /// Visit each horizon step with (free response + forced response of `qv`) - reference, and the
    /// step-response row g_b = d y_j / d q_b.
    fn sweep(&self, qv: &[f64; BLOCKS], mut visit: impl FnMut(f64, &[f64; BLOCKS])) {
        let mut preview = self.shaper.preview(self.sp, self.dt).skip(self.preview_skip);
        let (mut pw, mut forced) = (1.0, 0.0);
        let mut g = [0.0; BLOCKS];
        for j in 0..self.n {
            let b = self.block(j);
            pw *= self.a;
            forced = self.a * forced + self.gain * qv[b];
            for gb in g.iter_mut() {
                *gb *= self.a;
            }
            g[b] += self.gain;
            let free = pw * self.y0 + (1.0 - pw) * self.c;
            let r = preview.next().unwrap_or(self.sp);
            visit(free + forced - r, &g);
        }
    }

    fn weight(&self, e: f64) -> f64 {
        if e > 0.0 { self.overshoot_weight } else { 1.0 }
    }

    fn moves(&self, qv: &[f64; BLOCKS]) -> [f64; BLOCKS] {
        let mut dq = [0.0; BLOCKS];
        for b in 0..BLOCKS {
            dq[b] = qv[b] - if b == 0 { self.q_prev } else { qv[b - 1] };
        }
        dq
    }

    fn cost(&self, qv: &[f64; BLOCKS]) -> f64 {
        let mut track = 0.0;
        self.sweep(qv, |e, _| track += self.weight(e) * e * e);
        track / self.n as f64 + self.move_weight * self.moves(qv).iter().map(|d| d * d).sum::<f64>()
    }

    #[allow(clippy::needless_range_loop, reason = "index form mirrors the matrix algebra")]
    fn solve(&self, lo: f64, hi: f64) -> ([f64; BLOCKS], u32) {
        let mut qv = [self.q_prev.clamp(lo, hi); BLOCKS];
        let inv_n = 1.0 / self.n as f64;
        let mut iters = 0;
        for _ in 0..30 {
            iters += 1;
            // Gradient and generalised Hessian at the current sign pattern.
            let mut grad = [0.0; BLOCKS];
            let mut hess = [[0.0; BLOCKS]; BLOCKS];
            self.sweep(&qv, |e, g| {
                let w = self.weight(e);
                for b in 0..BLOCKS {
                    grad[b] += 2.0 * inv_n * w * e * g[b];
                    for c in 0..=b {
                        hess[b][c] += 2.0 * inv_n * w * g[b] * g[c];
                    }
                }
            });
            let dq = self.moves(&qv);
            for b in 0..BLOCKS {
                let next = if b + 1 < BLOCKS { dq[b + 1] } else { 0.0 };
                grad[b] += 2.0 * self.move_weight * (dq[b] - next);
                hess[b][b] += 2.0 * self.move_weight * if b + 1 < BLOCKS { 2.0 } else { 1.0 };
                if b > 0 {
                    hess[b][b - 1] -= 2.0 * self.move_weight;
                }
                for c in 0..b {
                    hess[c][b] = hess[b][c];
                }
            }

            let step = box_qp(&hess, &grad, &qv, lo, hi);
            let slope: f64 = (0..BLOCKS).map(|b| grad[b] * step[b]).sum();
            if slope > -1e-14 {
                break;
            }
            let j0 = self.cost(&qv);
            let mut t = 1.0;
            let trial = loop {
                let trial: [f64; BLOCKS] = core::array::from_fn(|b| qv[b] + t * step[b]);
                if self.cost(&trial) <= j0 + 1e-4 * t * slope || t < 1e-6 {
                    break trial;
                }
                t *= 0.5;
            };
            let moved = (0..BLOCKS).map(|b| (trial[b] - qv[b]).abs()).fold(0.0, f64::max);
            qv = trial;
            if moved < 1e-9 {
                break;
            }
        }
        (qv, iters)
    }
}

/// min_p 0.5 p'Hp + g'p  s.t.  lo <= q + p <= hi, by projected Gauss-Seidel (H is SPD: the move
/// penalty makes the diagonal strictly positive).
fn box_qp(h: &[[f64; BLOCKS]; BLOCKS], g: &[f64; BLOCKS], q: &[f64; BLOCKS], lo: f64, hi: f64) -> [f64; BLOCKS] {
    let mut p = [0.0; BLOCKS];
    for _ in 0..500 {
        let mut change: f64 = 0.0;
        for b in 0..BLOCKS {
            let hp: f64 = (0..BLOCKS).map(|c| h[b][c] * p[c]).sum();
            let new = (p[b] - (g[b] + hp) / h[b][b]).clamp(lo - q[b], hi - q[b]);
            change = change.max((new - p[b]).abs());
            p[b] = new;
        }
        if change < 1e-13 {
            break;
        }
    }
    p
}

/// Fixed-capacity deque of past airflow commands (no alloc).
#[derive(Clone, Debug)]
struct Past {
    buf: [f64; PAST_CAP],
    head: usize,
    len: usize,
}

impl Default for Past {
    fn default() -> Self {
        Self::DEFAULT
    }
}

impl Past {
    pub const DEFAULT: Self = Self {
        buf: [0.0; PAST_CAP],
        head: 0,
        len: 0,
    };
}

impl Past {
    fn len(&self) -> usize {
        self.len
    }

    fn push_front(&mut self, v: f64) {
        self.head = (self.head + PAST_CAP - 1) % PAST_CAP;
        self.buf[self.head] = v;
        self.len = (self.len + 1).min(PAST_CAP);
    }

    fn push_back(&mut self, v: f64) {
        if self.len == PAST_CAP {
            self.head = (self.head + 1) % PAST_CAP;
            self.len -= 1;
        }
        self.buf[(self.head + self.len) % PAST_CAP] = v;
        self.len += 1;
    }

    fn keep_last(&mut self, n: usize) {
        if self.len > n {
            self.head = (self.head + self.len - n) % PAST_CAP;
            self.len = n;
        }
    }

    /// 0 = newest.
    fn back(&self, i: usize) -> f64 {
        self.buf[(self.head + self.len - 1 - i) % PAST_CAP]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn past_deque() {
        let mut p = Past::default();
        p.push_back(1.0);
        p.push_front(0.0);
        p.push_back(2.0);
        assert_eq!((p.len(), p.back(0), p.back(2)), (3, 2.0, 0.0));
        p.keep_last(2);
        assert_eq!((p.len(), p.back(1)), (2, 1.0));
    }

    #[test]
    fn box_qp_matches_unconstrained_and_clamps() {
        let mut h = [[0.0; BLOCKS]; BLOCKS];
        for (b, row) in h.iter_mut().enumerate() {
            row[b] = 2.0;
        }
        let g = [-2.0, -4.0, 2.0, 0.0, -100.0, 100.0];
        let p = box_qp(&h, &g, &[0.0; BLOCKS], -10.0, 10.0);
        assert_eq!(p, [1.0, 2.0, -1.0, 0.0, 10.0, -10.0]);
    }

    /// Closed loop against the FOPDT plant itself plus an unmodelled -15F disturbance (e.g. wind):
    /// the disturbance estimate must remove the offset, and the airflow must settle where the plant
    /// needs it (q_ff + 15/K).
    #[test]
    fn offset_free_against_unmodelled_disturbance() {
        let ff = |_t: f64| 1.0;
        let m = Schedule::default().at(225.0);
        let (dt, a) = (10.0, exp(-10.0 / m.tau_s));
        let delay = round(m.theta_s / dt) as usize;
        let mut mpc = Mpc::default();
        let (mut y, mut hist) = (225.0, [1.0; 64]);
        for k in 0..2000 {
            let obs = Obs {
                pit_f: y,
                sp_f: 225.0,
                lid: false,
                q_min: 0.0,
                q_max: 4.0,
            };
            let q = mpc.step(&obs, &ff, dt);
            hist[k % 64] = q;
            let q_delayed = hist[(k + 64 - delay) % 64];
            y = a * y + (1.0 - a) * (225.0 + m.k * (q_delayed - 1.0) - 15.0);
        }
        assert!((y - 225.0).abs() < 0.05, "y = {y}");
        assert!((mpc.q_prev - (1.0 + 15.0 / m.k)).abs() < 1e-3, "q = {}", mpc.q_prev);
        assert!((mpc.disturbance_f() + 15.0).abs() < 0.5, "d = {}", mpc.disturbance_f());
    }

    #[test]
    fn respects_bounds_far_below_setpoint() {
        let ff = |_t: f64| 1.0;
        let mut mpc = Mpc::default();
        let obs = Obs {
            pit_f: 100.0,
            sp_f: 225.0,
            lid: false,
            q_min: 0.1,
            q_max: 2.5,
        };
        for _ in 0..50 {
            let q = mpc.step(&obs, &ff, 10.0);
            assert!((0.1..=2.5).contains(&q));
        }
    }
}
